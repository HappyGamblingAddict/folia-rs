//! End dimension generation.
//!
//! Ports the shipped `worldgen/noise_settings/end.json` router, the
//! `DensityFunctions.EndIslandDensityFunction` island field, and
//! `TheEndBiomeSource`. The central island and the outer island ring both come
//! from the shipped density functions; the obsidian arrival platform is placed
//! at vanilla's `(100, 49, 0)` feature origin.
//!
//! Parity notes:
//! - Like the Nether, the End uses `legacy_random_source: true`. The island
//!   field is exact (`LegacyRandomSource(seed)`, `consumeCount(17292)`,
//!   `SimplexNoise`), while the `end/base_3d_noise` blended noise is built from
//!   the world seed through the public positional API instead of a sequential
//!   `LegacyRandomSource`. Terrain is deterministic and the island layout is
//!   correct, but not guaranteed block-identical to Java.
//! - The dragon arena is data: ten deterministic obsidian spikes from
//!   `SpikeFeature.SpikeCacheLoader`, the exit-platform podium radius, and the
//!   central-island arena bounds. Cross-chunk spike writes are generated by
//!   every chunk the spike bounds intersect so per-chunk generation is complete.
//! - `chorus_plant`, `end_gateway`, `end_platform`, and `end_spike` are still
//!   explicit unsupported types in the shared configured-feature registry. This
//!   module provides an id-keyed dispatch for the usable pieces and fails
//!   loudly for the rest; end cities themselves remain unimplemented.

use crate::chunk::{BlockState, Chunk, ChunkSection, PalettedContainer};
use crate::worldgen::generator::sample_grid;
use crate::worldgen::noise::BlendedNoise;
use crate::worldgen::simplex::SimplexNoise;
use folia_math::BlockPos;
use folia_random::{LegacyRandomSource, RandomSource, XoroshiroRandomSource};
use std::fmt;
use std::io;

pub const MIN_Y: i32 = 0;
pub const HEIGHT: i32 = 128;
/// The End dimension type is 256 blocks tall; the noise column is 128 blocks.
pub const DIMENSION_HEIGHT: i32 = 256;
pub const SEA_LEVEL: i32 = 0;
pub const PLATFORM_ORIGIN: (i32, i32, i32) = (100, 49, 0);

/// `SpikeFeature.NUMBER_OF_SPIKES`.
pub const SPIKE_COUNT: usize = 10;
/// `SpikeFeature.SPIKE_DISTANCE`.
pub const SPIKE_RING_RADIUS: i32 = 42;
/// Exit podium radius (`EndPodiumFeature.PODIUM_RADIUS`).
pub const EXIT_PODIUM_RADIUS: i32 = 4;
/// The return gateway exits at the obsidian platform.
pub const RETURN_GATEWAY_EXIT: (i32, i32, i32) = (100, 50, 0);

/// The central-island dragon arena bounds. Vanilla has no single named constant
/// for this; the shipped density field makes the central island roughly 100
/// blocks in radius, the spike ring sits at 42, and the noise column ends at
/// y=128.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct DragonArena {
    pub center_x: i32,
    pub center_z: i32,
    pub radius: i32,
    pub min_y: i32,
    pub max_y: i32,
    pub spike_radius: i32,
    pub exit_podium_radius: i32,
}

pub const DRAGON_ARENA: DragonArena = DragonArena {
    center_x: 0,
    center_z: 0,
    radius: 100,
    min_y: MIN_Y,
    max_y: HEIGHT,
    spike_radius: SPIKE_RING_RADIUS,
    exit_podium_radius: EXIT_PODIUM_RADIUS,
};

impl DragonArena {
    pub fn contains(&self, x: i32, z: i32) -> bool {
        let dx = i64::from(x - self.center_x);
        let dz = i64::from(z - self.center_z);
        dx * dx + dz * dz <= i64::from(self.radius) * i64::from(self.radius)
    }

    pub fn contains_y(&self, y: i32) -> bool {
        (self.min_y..self.max_y).contains(&y)
    }
}

/// One `SpikeFeature.EndSpike`. `center_x`/`center_z` are absolute block
/// coordinates, `height` is the top obsidian Y (exclusive pillar bound), and
/// `guarded` pillars carry the iron-bar cage.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct EndSpike {
    pub center_x: i32,
    pub center_z: i32,
    pub radius: i32,
    pub height: i32,
    pub guarded: bool,
}

impl EndSpike {
    pub fn chunk_x(self) -> i32 {
        self.center_x.div_euclid(16)
    }

    pub fn chunk_z(self) -> i32 {
        self.center_z.div_euclid(16)
    }

    /// The end-crystal position spawned above the pillar
    /// (`EndCrystal.blockPosition` after snapping to the pillar centre).
    pub fn crystal_position(self) -> (i32, i32, i32) {
        (self.center_x, self.height + 1, self.center_z)
    }

    pub fn intersects_chunk(self, chunk_x: i32, chunk_z: i32) -> bool {
        let min_x = self.center_x - self.radius;
        let max_x = self.center_x + self.radius;
        let min_z = self.center_z - self.radius;
        let max_z = self.center_z + self.radius;
        let chunk_min_x = chunk_x * 16;
        let chunk_min_z = chunk_z * 16;
        max_x >= chunk_min_x
            && min_x < chunk_min_x + 16
            && max_z >= chunk_min_z
            && min_z < chunk_min_z + 16
    }
}

/// `end_gateway` configuration plus its generated block position.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct EndGateway {
    pub origin: (i32, i32, i32),
    pub exit: Option<(i32, i32, i32)>,
    pub exact: bool,
}

impl EndGateway {
    /// `minecraft:end_gateway_return`: exact exit at the obsidian platform.
    pub const fn returning(origin: (i32, i32, i32)) -> Self {
        Self {
            origin,
            exit: Some(RETURN_GATEWAY_EXIT),
            exact: true,
        }
    }

    /// `minecraft:end_gateway_delayed`: no fixed exit, computed on first use.
    pub const fn delayed(origin: (i32, i32, i32)) -> Self {
        Self {
            origin,
            exit: None,
            exact: false,
        }
    }
}

/// The block-entity payload the gateway feature would write.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct EndGatewayBlockEntity {
    pub position: (i32, i32, i32),
    pub exit: Option<(i32, i32, i32)>,
    pub exact: bool,
}

/// Explicit failures for End feature dispatch.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum EndFeatureError {
    Unsupported {
        feature: String,
    },
    OutOfRegion {
        feature: String,
        position: (i32, i32, i32),
    },
}

impl fmt::Display for EndFeatureError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            EndFeatureError::Unsupported { feature } => {
                write!(
                    formatter,
                    "End configured feature `{feature}` has no Rust implementation"
                )
            }
            EndFeatureError::OutOfRegion { feature, position } => write!(
                formatter,
                "End configured feature `{feature}` origin {position:?} is outside the generated chunk"
            ),
        }
    }
}

impl std::error::Error for EndFeatureError {}

const CELL_WIDTH: i32 = 8;
const CELL_HEIGHT: i32 = 4;
const END_STONE: &str = "minecraft:end_stone";

pub struct EndGenerator {
    seed: i64,
    islands: EndIslandDensity,
    base_noise: BlendedNoise,
    spikes: Vec<EndSpike>,
}

impl EndGenerator {
    pub fn new(seed: i64) -> io::Result<Self> {
        let mut random = XoroshiroRandomSource::new(seed);
        let base_noise = BlendedNoise::create(&mut random, 0.25, 0.25, 80.0, 160.0, 4.0);
        Ok(Self {
            seed,
            islands: EndIslandDensity::new(seed),
            base_noise,
            spikes: end_spikes_for_seed(seed),
        })
    }

    pub fn seed(&self) -> i64 {
        self.seed
    }

    pub fn min_y(&self) -> i32 {
        MIN_Y
    }

    pub fn height(&self) -> i32 {
        HEIGHT
    }

    /// `TheEndBiomeSource.getNoiseBiome` for a quart position.
    pub fn biome_at_quart(&self, quart_x: i32, quart_y: i32, quart_z: i32) -> &'static str {
        let _ = quart_y;
        let section_x = quart_x >> 2;
        let section_z = quart_z >> 2;
        if i64::from(section_x) * i64::from(section_x) + i64::from(section_z) * i64::from(section_z)
            <= 4096
        {
            return "minecraft:the_end";
        }
        let x = (section_x * 2 + 1) * 8;
        let z = (section_z * 2 + 1) * 8;
        let erosion = self.islands.compute(x, z);
        if erosion > 0.25 {
            "minecraft:end_highlands"
        } else if erosion >= -0.0625 {
            "minecraft:end_midlands"
        } else if erosion < -0.21875 {
            "minecraft:small_end_islands"
        } else {
            "minecraft:end_barrens"
        }
    }

    pub fn biome_at_block(&self, x: i32, y: i32, z: i32) -> &'static str {
        self.biome_at_quart(x >> 2, y >> 2, z >> 2)
    }

    /// `DensityFunctions.EndIslandDensityFunction.compute` at a block position.
    pub fn island_density(&self, x: i32, z: i32) -> f64 {
        self.islands.compute(x, z)
    }

    /// Final End density at one block position (`postProcess(slideEnd(
    /// sloped_cheese))`), before the 8x4x8 interpolation grid.
    pub fn density(&self, x: i32, y: i32, z: i32) -> f64 {
        let sloped = self.islands.compute(x, z)
            + self
                .base_noise
                .compute(f64::from(x), f64::from(y), f64::from(z));
        let top_gradient = clamped_map(f64::from(y), 56.0, 312.0, 1.0, 0.0);
        let top = lerp(top_gradient, -23.4375, sloped);
        let bottom_gradient = clamped_map(f64::from(y), 4.0, 32.0, 0.0, 1.0);
        let slid = lerp(bottom_gradient, -0.234375, top);
        let value = (0.64 * slid).clamp(-1.0, 1.0);
        value / 2.0 - value * value * value / 24.0
    }

    pub fn generate_chunk(&self, chunk_x: i32, chunk_z: i32) -> io::Result<Chunk> {
        let cells_x = (16 / CELL_WIDTH + 1) as usize;
        let cells_z = cells_x;
        let cells_y = (HEIGHT / CELL_HEIGHT + 1) as usize;
        let mut grid = vec![0.0f64; cells_x * cells_z * cells_y];
        for xi in 0..cells_x {
            for zi in 0..cells_z {
                for yi in 0..cells_y {
                    let x = chunk_x * 16 + xi as i32 * CELL_WIDTH;
                    let y = MIN_Y + yi as i32 * CELL_HEIGHT;
                    let z = chunk_z * 16 + zi as i32 * CELL_WIDTH;
                    grid[(xi * cells_z + zi) * cells_y + yi] = self.density(x, y, z);
                }
            }
        }

        let section_count = DIMENSION_HEIGHT / 16;
        let mut sections = Vec::with_capacity(section_count as usize);
        for index in 0..section_count {
            sections.push(ChunkSection {
                y: (MIN_Y.div_euclid(16) + index) as i8,
                block_states: PalettedContainer {
                    palette: vec![air()],
                    indices: vec![0; 4096],
                },
                biomes: Some(PalettedContainer {
                    palette: vec!["minecraft:the_end".into()],
                    indices: vec![0; 64],
                }),
                light: crate::light::SectionLight::default(),
            });
        }
        let mut chunk = Chunk {
            x: chunk_x,
            z: chunk_z,
            sections,
        };

        let end_stone = BlockState {
            name: END_STONE.into(),
            properties: vec![],
        };
        for local_x in 0..16 {
            for local_z in 0..16 {
                for index in 0..HEIGHT {
                    let y = MIN_Y + index;
                    let value = sample_grid(
                        &grid,
                        cells_x,
                        cells_z,
                        cells_y,
                        CELL_WIDTH,
                        CELL_HEIGHT,
                        local_x,
                        local_z,
                        index,
                    );
                    if value > 0.0 {
                        chunk.set_block_state_ref(
                            local_x as usize,
                            y,
                            local_z as usize,
                            &end_stone,
                        );
                    }
                }
            }
        }

        self.fill_biomes(&mut chunk, chunk_x, chunk_z);
        self.place_platform(&mut chunk);
        self.place_spikes(&mut chunk);
        Ok(chunk)
    }

    /// The deterministic `SpikeFeature` list for this seed.
    pub fn spikes(&self) -> &[EndSpike] {
        &self.spikes
    }

    /// Places the local slice of every spike whose bounds intersect this chunk.
    /// Vanilla triggers the feature only from the spike's centre chunk and
    /// writes into a `WorldGenRegion`; standalone per-chunk generation writes
    /// the same final blocks by visiting the intersecting chunks directly.
    pub fn place_spikes(&self, chunk: &mut Chunk) {
        for spike in &self.spikes {
            if spike.intersects_chunk(chunk.x, chunk.z) {
                place_spike(chunk, *spike);
            }
        }
    }

    /// Places `EndPlatformFeature.createEndPlatform` for every chunk the
    /// vanilla `(100, 49, 0)` 5x5 platform overlaps.
    fn place_platform(&self, chunk: &mut Chunk) {
        place_end_platform(
            chunk,
            BlockPos::new(PLATFORM_ORIGIN.0, PLATFORM_ORIGIN.1, PLATFORM_ORIGIN.2),
        );
    }

    fn fill_biomes(&self, chunk: &mut Chunk, chunk_x: i32, chunk_z: i32) {
        let quart_layers = (DIMENSION_HEIGHT >> 2) as usize;
        let mut cursor = 0usize;
        for section in &mut chunk.sections {
            let mut palette: Vec<String> = Vec::new();
            let mut indices = Vec::with_capacity(64);
            for _ in 0..64 {
                let layer = cursor / 16;
                let quart_y = layer;
                let qz = (cursor % 16) / 4;
                let qx = cursor % 4;
                let biome = self
                    .biome_at_quart(
                        chunk_x * 4 + qx as i32,
                        quart_y as i32,
                        chunk_z * 4 + qz as i32,
                    )
                    .to_owned();
                cursor += 1;
                let index = match palette.iter().position(|value| value == &biome) {
                    Some(index) => index,
                    None => {
                        palette.push(biome);
                        palette.len() - 1
                    }
                };
                indices.push(index as u16);
            }
            section.biomes = Some(PalettedContainer { palette, indices });
        }
        debug_assert_eq!(cursor, quart_layers * 16);
    }
}

/// `SpikeFeature.getSpikesForLevel` + `SpikeCacheLoader`.
pub fn end_spikes_for_seed(seed: i64) -> Vec<EndSpike> {
    let mut seed_random = LegacyRandomSource::new(seed);
    let cache_key = seed_random.next_long() & 65535;
    let mut random = LegacyRandomSource::new(cache_key);

    let mut shuffled: Vec<i32> = (0..SPIKE_COUNT as i32).collect();
    for i in (2..=SPIKE_COUNT as i32).rev() {
        let pick = random.next_int_bound(i);
        shuffled.swap((i - 1) as usize, pick as usize);
    }

    let mut spikes = Vec::with_capacity(SPIKE_COUNT);
    for (index, rank) in shuffled.iter().copied().enumerate() {
        let angle = 2.0 * (-std::f64::consts::PI + (std::f64::consts::PI / 10.0) * index as f64);
        let center_x = (42.0 * angle.cos()).floor() as i32;
        let center_z = (42.0 * angle.sin()).floor() as i32;
        spikes.push(EndSpike {
            center_x,
            center_z,
            radius: 2 + rank / 3,
            height: 76 + rank * 3,
            guarded: rank == 1 || rank == 2,
        });
    }
    spikes
}

/// `EndPlatformFeature.createEndPlatform` without the block-drop variant.
pub fn place_end_platform(chunk: &mut Chunk, origin: BlockPos) -> bool {
    let origin_x = origin.x();
    let origin_y = origin.y();
    let origin_z = origin.z();
    let min_x = origin_x - 2;
    let max_x = origin_x + 2;
    let min_z = origin_z - 2;
    let max_z = origin_z + 2;
    let chunk_min_x = chunk.x * 16;
    let chunk_min_z = chunk.z * 16;
    if max_x < chunk_min_x
        || min_x >= chunk_min_x + 16
        || max_z < chunk_min_z
        || min_z >= chunk_min_z + 16
    {
        return false;
    }
    let obsidian = BlockState {
        name: "minecraft:obsidian".into(),
        properties: vec![],
    };
    for z in min_z..=max_z {
        for x in min_x..=max_x {
            let local_x = x - chunk_min_x;
            let local_z = z - chunk_min_z;
            if !(0..16).contains(&local_x) || !(0..16).contains(&local_z) {
                continue;
            }
            // `i2 == -1` is obsidian; the three layers above are cleared.
            chunk.set_block_state_ref(local_x as usize, origin_y - 1, local_z as usize, &obsidian);
            for y in origin_y..origin_y + 3 {
                chunk.set_block_state(local_x as usize, y, local_z as usize, air());
            }
        }
    }
    true
}

/// `SpikeFeature.placeSpike`: the obsidian pillar, the air clear above y=65,
/// the optional iron-bar cage, and the crystal support/fire blocks.
pub fn place_spike(chunk: &mut Chunk, spike: EndSpike) {
    let radius = spike.radius;
    let chunk_min_x = chunk.x * 16;
    let chunk_min_z = chunk.z * 16;
    let min_x = spike.center_x - radius;
    let max_x = spike.center_x + radius;
    let min_z = spike.center_z - radius;
    let max_z = spike.center_z + radius;
    let max_y = (spike.height + 10).min(DIMENSION_HEIGHT - 1);

    let obsidian = BlockState {
        name: "minecraft:obsidian".into(),
        properties: vec![],
    };
    for y in MIN_Y..=max_y {
        for z in min_z..=max_z {
            let local_z = z - chunk_min_z;
            if !(0..16).contains(&local_z) {
                continue;
            }
            for x in min_x..=max_x {
                let local_x = x - chunk_min_x;
                if !(0..16).contains(&local_x) {
                    continue;
                }
                let dx = i64::from(x - spike.center_x);
                let dz = i64::from(z - spike.center_z);
                let within = dx * dx + dz * dz <= i64::from(radius) * i64::from(radius) + 1;
                if within && y < spike.height {
                    chunk.set_block_state_ref(local_x as usize, y, local_z as usize, &obsidian);
                } else if y > 65 {
                    chunk.set_block_state(local_x as usize, y, local_z as usize, air());
                }
            }
        }
    }

    if spike.guarded {
        for z_offset in -2i32..=2 {
            for x_offset in -2i32..=2 {
                for y_offset in 0..=3 {
                    let outer_x = x_offset.abs() == 2;
                    let outer_z = z_offset.abs() == 2;
                    let top = y_offset == 3;
                    if !(outer_x || outer_z || top) {
                        continue;
                    }
                    let north_axis = x_offset == -2 || x_offset == 2 || top;
                    let east_axis = z_offset == -2 || z_offset == 2 || top;
                    let state = BlockState {
                        name: "minecraft:iron_bars".into(),
                        properties: vec![
                            ("waterlogged".into(), "false".into()),
                            ("north".into(), bool_property(north_axis && z_offset != -2)),
                            ("south".into(), bool_property(north_axis && z_offset != 2)),
                            ("west".into(), bool_property(east_axis && x_offset != -2)),
                            ("east".into(), bool_property(east_axis && x_offset != 2)),
                        ],
                    };
                    set_local(
                        chunk,
                        spike.center_x + x_offset,
                        spike.height + y_offset,
                        spike.center_z + z_offset,
                        state,
                    );
                }
            }
        }
    }

    // `EndCrystal.blockPosition()` sits one block above the spike; vanilla
    // writes bedrock underneath it and fire in its cell. The crystal entity
    // itself is returned as data through `EndSpike::crystal_position`.
    let (crystal_x, crystal_y, crystal_z) = spike.crystal_position();
    set_local(
        chunk,
        crystal_x,
        crystal_y - 1,
        crystal_z,
        BlockState {
            name: "minecraft:bedrock".into(),
            properties: vec![],
        },
    );
    set_local(
        chunk,
        crystal_x,
        crystal_y,
        crystal_z,
        BlockState {
            name: "minecraft:fire".into(),
            properties: vec![],
        },
    );
}

/// `EndGatewayFeature.place` block construction. Returns the gateway block
/// entity data when the centre cell lies inside this chunk.
pub fn place_end_gateway(chunk: &mut Chunk, gateway: &EndGateway) -> Option<EndGatewayBlockEntity> {
    let (origin_x, origin_y, origin_z) = gateway.origin;
    let mut block_entity = None;
    for dy in -2..=2 {
        for dz in -1..=1 {
            for dx in -1..=1 {
                let x = origin_x + dx;
                let y = origin_y + dy;
                let z = origin_z + dz;
                let on_x = dx == 0;
                let on_y = dy == 0;
                let on_z = dz == 0;
                let vertical_cap = dy.abs() == 2;
                let bedrock_ring = if vertical_cap {
                    on_x && on_z
                } else {
                    on_x || on_z
                };
                let state = if on_x && on_y && on_z {
                    block_entity = Some(EndGatewayBlockEntity {
                        position: (x, y, z),
                        exit: gateway.exit,
                        exact: gateway.exact,
                    });
                    state("minecraft:end_gateway")
                } else if on_y {
                    air()
                } else if bedrock_ring {
                    state("minecraft:bedrock")
                } else {
                    air()
                };
                set_local(chunk, x, y, z, state);
            }
        }
    }
    block_entity
}

/// `ChorusPlantFeature.place` + `ChorusFlowerBlock.generatePlant`.
pub fn place_chorus_plant(
    chunk: &mut Chunk,
    origin: (i32, i32, i32),
    random: &mut impl RandomSource,
) -> bool {
    let (x, y, z) = origin;
    if !in_chunk(chunk, x, y, z) || !is_empty(chunk, x, y, z) {
        return false;
    }
    let below = block_at(chunk, x, y - 1, z);
    if below.is_none_or(|state| state.name != END_STONE) {
        return false;
    }

    set_local(chunk, x, y, z, chorus_plant_state(chunk, x, y, z));
    let mut context = ChorusGrowth {
        origin: (x, y, z),
        max_horizontal_distance: 8,
        placed: vec![(x, y, z)],
    };
    grow_chorus(chunk, (x, y, z), random, &mut context, 0);

    // `WorldGenRegion.setBlock` uses flag 2 (no neighbour updates), and a
    // standalone chunk has no scheduled shape refresh. Recompute the final
    // connection properties once after growth so the saved chunk is coherent.
    let placements = context.placed.clone();
    for (plant_x, plant_y, plant_z) in placements {
        let Some(state) = block_at(chunk, plant_x, plant_y, plant_z) else {
            continue;
        };
        if state.name == "minecraft:chorus_plant" {
            set_local(
                chunk,
                plant_x,
                plant_y,
                plant_z,
                chorus_plant_state(chunk, plant_x, plant_y, plant_z),
            );
        }
    }
    true
}

struct ChorusGrowth {
    origin: (i32, i32, i32),
    max_horizontal_distance: i32,
    placed: Vec<(i32, i32, i32)>,
}

fn grow_chorus(
    chunk: &mut Chunk,
    branch_pos: (i32, i32, i32),
    random: &mut impl RandomSource,
    context: &mut ChorusGrowth,
    iterations: i32,
) {
    let mut trunk = random.next_int_bound(4) + 1;
    if iterations == 0 {
        trunk += 1;
    }

    for offset in 0..trunk {
        let pos = (branch_pos.0, branch_pos.1 + offset + 1, branch_pos.2);
        if !all_neighbors_empty(chunk, pos, None) {
            return;
        }
        set_chorus_plant(chunk, pos, context);
        set_chorus_plant(chunk, (pos.0, pos.1 - 1, pos.2), context);
    }

    let mut branched = false;
    if iterations < 4 {
        let mut branch_count = random.next_int_bound(4);
        if iterations == 0 {
            branch_count += 1;
        }
        for _ in 0..branch_count {
            let direction = horizontal_direction(random);
            let pos = (
                branch_pos.0 + direction.0,
                branch_pos.1 + trunk,
                branch_pos.2 + direction.2,
            );
            let opposite = (-direction.0, 0, -direction.2);
            if (pos.0 - context.origin.0).abs() < context.max_horizontal_distance
                && (pos.2 - context.origin.2).abs() < context.max_horizontal_distance
                && is_empty(chunk, pos.0, pos.1, pos.2)
                && is_empty(chunk, pos.0, pos.1 - 1, pos.2)
                && all_neighbors_empty(chunk, pos, Some(opposite))
            {
                branched = true;
                set_chorus_plant(chunk, pos, context);
                set_chorus_plant(
                    chunk,
                    (pos.0 + opposite.0, pos.1, pos.2 + opposite.2),
                    context,
                );
                grow_chorus(chunk, pos, random, context, iterations + 1);
            }
        }
    }

    if !branched {
        set_local(
            chunk,
            branch_pos.0,
            branch_pos.1 + trunk,
            branch_pos.2,
            BlockState {
                name: "minecraft:chorus_flower".into(),
                properties: vec![("age".into(), "5".into())],
            },
        );
    }
}

fn set_chorus_plant(chunk: &mut Chunk, pos: (i32, i32, i32), context: &mut ChorusGrowth) {
    if !in_chunk(chunk, pos.0, pos.1, pos.2) {
        return;
    }
    let state = chorus_plant_state(chunk, pos.0, pos.1, pos.2);
    set_local(chunk, pos.0, pos.1, pos.2, state);
    context.placed.push(pos);
}

fn chorus_plant_state(chunk: &Chunk, x: i32, y: i32, z: i32) -> BlockState {
    let down = is_chorus_connection(chunk, x, y - 1, z, true);
    let up = is_chorus_connection(chunk, x, y + 1, z, false);
    let north = is_chorus_connection(chunk, x, y, z - 1, false);
    let east = is_chorus_connection(chunk, x + 1, y, z, false);
    let south = is_chorus_connection(chunk, x, y, z + 1, false);
    let west = is_chorus_connection(chunk, x - 1, y, z, false);
    BlockState {
        name: "minecraft:chorus_plant".into(),
        properties: vec![
            ("down".into(), bool_property(down)),
            ("up".into(), bool_property(up)),
            ("north".into(), bool_property(north)),
            ("east".into(), bool_property(east)),
            ("south".into(), bool_property(south)),
            ("west".into(), bool_property(west)),
        ],
    }
}

fn is_chorus_connection(chunk: &Chunk, x: i32, y: i32, z: i32, down: bool) -> bool {
    match block_at(chunk, x, y, z) {
        Some(state) => {
            state.name == "minecraft:chorus_plant"
                || state.name == "minecraft:chorus_flower"
                || (down && state.name == END_STONE)
        }
        None => false,
    }
}

fn all_neighbors_empty(
    chunk: &Chunk,
    pos: (i32, i32, i32),
    excluding: Option<(i32, i32, i32)>,
) -> bool {
    for direction in [(0, 0, -1), (1, 0, 0), (0, 0, 1), (-1, 0, 0)] {
        if Some(direction) == excluding {
            continue;
        }
        if !is_empty(chunk, pos.0 + direction.0, pos.1, pos.2 + direction.2) {
            return false;
        }
    }
    true
}

fn horizontal_direction(random: &mut impl RandomSource) -> (i32, i32, i32) {
    match random.next_int_bound(4) {
        0 => (0, 0, -1),
        1 => (1, 0, 0),
        2 => (0, 0, 1),
        _ => (-1, 0, 0),
    }
}

/// Id-keyed explicit dispatch for the End configured features that have a
/// concrete implementation here. Everything else fails loudly instead of
/// silently skipping.
pub fn place_configured_feature(
    chunk: &mut Chunk,
    feature: &str,
    origin: (i32, i32, i32),
    random: &mut impl RandomSource,
) -> Result<bool, EndFeatureError> {
    match feature {
        "minecraft:chorus_plant" => Ok(place_chorus_plant(chunk, origin, random)),
        "minecraft:end_gateway_return" => {
            if !in_chunk(chunk, origin.0, origin.1, origin.2) {
                return Err(EndFeatureError::OutOfRegion {
                    feature: feature.to_owned(),
                    position: origin,
                });
            }
            place_end_gateway(chunk, &EndGateway::returning(origin));
            Ok(true)
        }
        "minecraft:end_gateway_delayed" => {
            if !in_chunk(chunk, origin.0, origin.1, origin.2) {
                return Err(EndFeatureError::OutOfRegion {
                    feature: feature.to_owned(),
                    position: origin,
                });
            }
            place_end_gateway(chunk, &EndGateway::delayed(origin));
            Ok(true)
        }
        "minecraft:end_platform" => Ok(place_end_platform(
            chunk,
            BlockPos::new(origin.0, origin.1, origin.2),
        )),
        other => Err(EndFeatureError::Unsupported {
            feature: other.to_owned(),
        }),
    }
}

fn in_chunk(chunk: &Chunk, x: i32, y: i32, z: i32) -> bool {
    let local_x = i64::from(x) - i64::from(chunk.x) * 16;
    let local_z = i64::from(z) - i64::from(chunk.z) * 16;
    (0..16).contains(&local_x)
        && (0..16).contains(&local_z)
        && (MIN_Y..DIMENSION_HEIGHT).contains(&y)
}

fn block_at(chunk: &Chunk, x: i32, y: i32, z: i32) -> Option<&BlockState> {
    let local_x = i64::from(x) - i64::from(chunk.x) * 16;
    let local_z = i64::from(z) - i64::from(chunk.z) * 16;
    if !(0..16).contains(&local_x) || !(0..16).contains(&local_z) {
        return None;
    }
    chunk.block_state(local_x as usize, y, local_z as usize)
}

fn is_empty(chunk: &Chunk, x: i32, y: i32, z: i32) -> bool {
    block_at(chunk, x, y, z).is_some_and(|state| crate::worldgen::feature::is_air_name(&state.name))
}

fn set_local(chunk: &mut Chunk, x: i32, y: i32, z: i32, state: BlockState) {
    if !in_chunk(chunk, x, y, z) {
        return;
    }
    let local_x = (i64::from(x) - i64::from(chunk.x) * 16) as usize;
    let local_z = (i64::from(z) - i64::from(chunk.z) * 16) as usize;
    chunk.set_block_state(local_x, y, local_z, state);
}

fn bool_property(value: bool) -> String {
    if value { "true".into() } else { "false".into() }
}

fn state(name: &str) -> BlockState {
    BlockState {
        name: name.into(),
        properties: vec![],
    }
}

/// `DensityFunctions.EndIslandDensityFunction`.
struct EndIslandDensity {
    noise: SimplexNoise,
}

impl EndIslandDensity {
    fn new(seed: i64) -> Self {
        let mut random = LegacyRandomSource::new(seed);
        random.consume_count(17292);
        Self {
            noise: SimplexNoise::new(&mut random),
        }
    }

    fn compute(&self, x: i32, z: i32) -> f64 {
        (f64::from(self.height_value(x / 8, z / 8)) - 8.0) / 128.0
    }

    fn height_value(&self, x: i32, z: i32) -> f32 {
        let i = x / 2;
        let i1 = z / 2;
        let i2 = x % 2;
        let i3 = z % 2;
        let mut value = 100.0
            - ((i64::from(x) * i64::from(x) + i64::from(z) * i64::from(z)) as f32).sqrt() * 8.0;
        value = value.clamp(-100.0, 80.0);

        for i4 in -12..=12 {
            for i5 in -12..=12 {
                let l = i + i4;
                let l1 = i1 + i5;
                let mut island = f32::MIN;
                if i64::from(l) * i64::from(l) + i64::from(l1) * i64::from(l1) > 4096
                    && (self.noise.get_value(f64::from(l), f64::from(l1)) as f32) < -0.9
                {
                    island = (l.abs() as f32 * 3439.0 + l1.abs() as f32 * 147.0) % 13.0 + 9.0;
                }
                if island != f32::MIN {
                    let f2 = (i2 - i4 * 2) as f32;
                    let f3 = (i3 - i5 * 2) as f32;
                    let f4 = (100.0 - (f2 * f2 + f3 * f3).sqrt() * island).clamp(-100.0, 80.0);
                    value = value.max(f4);
                }
            }
        }
        value
    }
}

fn clamped_map(
    input: f64,
    input_min: f64,
    input_max: f64,
    output_min: f64,
    output_max: f64,
) -> f64 {
    let inverse = (input - input_min) / (input_max - input_min);
    if inverse < 0.0 {
        output_min
    } else if inverse > 1.0 {
        output_max
    } else {
        output_min + inverse * (output_max - output_min)
    }
}

fn lerp(delta: f64, start: f64, end: f64) -> f64 {
    start + delta * (end - start)
}

