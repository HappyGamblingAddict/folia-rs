thread_local! {
    /// Template ids materialized by this thread. `is_loaded` is a diagnostic
    /// view rather than process-wide state, so one test or session cannot
    /// observe another thread's lazy load.
    static LOADED_TEMPLATES: RefCell<HashSet<String>> = RefCell::new(HashSet::new());
}

/// The generated village catalog embedded into the binary.
pub const EMBEDDED_STRUCTURE_TEMPLATES: &str =
    include_str!("../../../assets/structure_templates.json");

/// The generated non-village catalog embedded into the binary.
pub const EMBEDDED_STRUCTURE_TEMPLATES_MORE: &str =
    include_str!("../../../assets/structure_templates_more.json");

/// The generated trial-chamber catalog embedded into the binary.
pub const EMBEDDED_STRUCTURE_TEMPLATES_TRIAL: &str =
    include_str!("../../../assets/structure_templates_trial.json");

pub const TARGET_VERSION: &str = "1.21.11";
pub const TARGET_DATA_VERSION: i32 = 4788;

/// Errors raised while loading a catalog or materializing one template.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CatalogError {
    /// The embedded/supplied JSON is not valid JSON.
    InvalidJson(String),
    /// The JSON is valid but does not match the catalog schema or counts.
    InvalidCatalog(String),
    /// No template with the requested normalized id exists.
    UnknownTemplate { template: String },
    /// The entry exists but its base64 or gzip/NBT payload is damaged.
    CorruptPayload { template: String, message: String },
}

impl fmt::Display for CatalogError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            CatalogError::InvalidJson(message) => {
                write!(
                    formatter,
                    "invalid structure-template catalog JSON: {message}"
                )
            }
            CatalogError::InvalidCatalog(message) => {
                write!(formatter, "invalid structure-template catalog: {message}")
            }
            CatalogError::UnknownTemplate { template } => {
                write!(formatter, "unknown structure template `{template}`")
            }
            CatalogError::CorruptPayload { template, message } => write!(
                formatter,
                "structure template `{template}` has a corrupt payload: {message}"
            ),
        }
    }
}

impl std::error::Error for CatalogError {}

/// One shared family stream in the non-village catalog.
struct SharedBlob {
    name: String,
    /// Base64 of the gzip-compressed concatenation of every NBT document in
    /// the family. Kept encoded until the first template in the family is
    /// requested.
    payload: String,
    /// Length of the decompressed NBT concatenation, validated against the
    /// offset/length index while parsing the catalog.
    uncompressed_bytes: usize,
    decoded: OnceLock<Result<Vec<u8>, String>>,
}

impl Clone for SharedBlob {
    fn clone(&self) -> Self {
        Self {
            name: self.name.clone(),
            payload: self.payload.clone(),
            uncompressed_bytes: self.uncompressed_bytes,
            // Parsed bytes are immutable; a clone starts with an empty cache.
            decoded: OnceLock::new(),
        }
    }
}

impl fmt::Debug for SharedBlob {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("SharedBlob")
            .field("name", &self.name)
            .field("payload_bytes", &self.payload.len())
            .field("uncompressed_bytes", &self.uncompressed_bytes)
            .field("decoded", &self.decoded.get().is_some())
            .finish()
    }
}

enum CatalogPayload {
    Inline(String),
    Shared {
        blob: Arc<SharedBlob>,
        offset: usize,
        length: usize,
    },
}

impl Clone for CatalogPayload {
    fn clone(&self) -> Self {
        match self {
            CatalogPayload::Inline(payload) => CatalogPayload::Inline(payload.clone()),
            CatalogPayload::Shared {
                blob,
                offset,
                length,
            } => CatalogPayload::Shared {
                blob: Arc::clone(blob),
                offset: *offset,
                length: *length,
            },
        }
    }
}

impl fmt::Debug for CatalogPayload {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            CatalogPayload::Inline(payload) => formatter
                .debug_struct("Inline")
                .field("payload_bytes", &payload.len())
                .finish(),
            CatalogPayload::Shared {
                blob,
                offset,
                length,
            } => formatter
                .debug_struct("Shared")
                .field("blob", &blob.name)
                .field("offset", offset)
                .field("length", length)
                .finish(),
        }
    }
}

struct CatalogEntry {
    payload: CatalogPayload,
    parsed: OnceLock<Result<StructureTemplate, String>>,
}

impl Clone for CatalogEntry {
    fn clone(&self) -> Self {
        Self {
            payload: self.payload.clone(),
            // Parsed templates are immutable; a clone starts with an empty
            // cache so it never needs to clone the parsed trees.
            parsed: OnceLock::new(),
        }
    }
}

impl fmt::Debug for CatalogEntry {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("CatalogEntry")
            .field("payload", &self.payload)
            .field("parsed", &self.parsed.get().is_some())
            .finish()
    }
}

/// A lazy, cached view over one or more embedded catalogs.
///
/// [`StructureTemplateCatalog::shipped`] merges the village, non-village, and
/// trial-chamber catalogs. For backwards compatibility with the original
/// village-only asset pin, [`len`](Self::len), [`total_bytes`](Self::total_bytes),
/// and [`ids`](Self::ids) describe the primary village slice;
/// [`all_len`](Self::all_len), [`all_total_bytes`](Self::all_total_bytes), and
/// [`all_ids`](Self::all_ids) describe the village plus non-village catalogs;
/// [`merged_len`](Self::merged_len), [`merged_total_bytes`](Self::merged_total_bytes),
/// and [`merged_ids`](Self::merged_ids) describe every loaded catalog. Template
/// lookup always searches every loaded catalog.
#[derive(Clone)]
pub struct StructureTemplateCatalog {
    version: String,
    data_version: i32,
    total_bytes: usize,
    nbt_bytes: usize,
    primary_ids: BTreeSet<String>,
    primary_bytes: usize,
    secondary_ids: BTreeSet<String>,
    secondary_bytes: usize,
    entries: BTreeMap<String, CatalogEntry>,
}

impl fmt::Debug for StructureTemplateCatalog {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("StructureTemplateCatalog")
            .field("version", &self.version)
            .field("data_version", &self.data_version)
            .field("templates", &self.entries.len())
            .field("primary_templates", &self.primary_ids.len())
            .field("secondary_templates", &self.secondary_ids.len())
            .field("total_bytes", &self.total_bytes)
            .field("nbt_bytes", &self.nbt_bytes)
            .finish()
    }
}

impl StructureTemplateCatalog {
    /// Parses all embedded catalogs once and returns the merged value.
    pub fn shipped() -> &'static Self {
        static SHIPPED: OnceLock<StructureTemplateCatalog> = OnceLock::new();
        SHIPPED.get_or_init(|| {
            let mut catalog =
                Self::from_json(EMBEDDED_STRUCTURE_TEMPLATES).unwrap_or_else(|error| {
                    panic!("embedded structure_templates.json is invalid: {error}")
                });
            let more = Self::from_indexed_json(EMBEDDED_STRUCTURE_TEMPLATES_MORE).unwrap_or_else(
                |error| panic!("embedded structure_templates_more.json is invalid: {error}"),
            );
            catalog.merge(more).unwrap_or_else(|error| {
                panic!("embedded structure-template catalogs conflict: {error}")
            });
            let trial = Self::from_indexed_json(EMBEDDED_STRUCTURE_TEMPLATES_TRIAL).unwrap_or_else(
                |error| panic!("embedded structure_templates_trial.json is invalid: {error}"),
            );
            catalog.merge_additional(trial).unwrap_or_else(|error| {
                panic!("embedded trial-chamber catalog conflicts: {error}")
            });
            catalog
        })
    }

    /// Parses a per-template catalog document and validates its schema,
    /// counts, and base64 payload sizes without decompressing any NBT.
    pub fn from_json(text: &str) -> Result<Self, CatalogError> {
        let value: Value = serde_json::from_str(text)
            .map_err(|error| CatalogError::InvalidJson(error.to_string()))?;
        let root = value
            .as_object()
            .ok_or_else(|| invalid_catalog("root must be an object"))?;
        reject_unknown_keys(
            root,
            &[
                "counts",
                "data_version",
                "templates",
                "total_bytes",
                "version",
            ],
            "catalog",
        )?;

        let version = required_str(root, "version", "catalog")?.to_owned();
        if version != TARGET_VERSION {
            return Err(invalid_catalog(format!(
                "version {version} does not match target {TARGET_VERSION}"
            )));
        }
        let data_version = required_i32(root, "data_version", "catalog")?;
        if data_version != TARGET_DATA_VERSION {
            return Err(invalid_catalog(format!(
                "data version {data_version} does not match target {TARGET_DATA_VERSION}"
            )));
        }
        let total_bytes = required_usize(root, "total_bytes", "catalog")?;

        let template_count = parse_counts(root)?;

        let templates = required_object(root, "templates", "catalog")?;
        let mut entries = BTreeMap::new();
        let mut decoded_bytes = 0usize;
        for (name, value) in templates {
            let id = normalize_structure_id(name);
            if id != *name {
                return Err(invalid_catalog(format!(
                    "template key `{name}` is not normalized (expected `{id}`)"
                )));
            }
            let payload = value.as_str().ok_or_else(|| {
                invalid_catalog(format!("template `{id}` payload must be a base64 string"))
            })?;
            decoded_bytes = decoded_bytes.saturating_add(
                validate_base64(payload)
                    .map_err(|message| invalid_catalog(format!("template `{id}`: {message}")))?,
            );
            if entries
                .insert(
                    id.clone(),
                    CatalogEntry {
                        payload: CatalogPayload::Inline(payload.to_owned()),
                        parsed: OnceLock::new(),
                    },
                )
                .is_some()
            {
                return Err(invalid_catalog(format!("duplicate template id `{id}`")));
            }
        }

        if entries.len() != template_count {
            return Err(invalid_catalog(format!(
                "catalog has {} templates but counts.templates is {template_count}",
                entries.len()
            )));
        }
        if decoded_bytes != total_bytes {
            return Err(invalid_catalog(format!(
                "catalog payloads decode to {decoded_bytes} bytes but total_bytes is {total_bytes}"
            )));
        }

        let primary_ids = entries.keys().cloned().collect();
        Ok(Self {
            version,
            data_version,
            total_bytes,
            nbt_bytes: 0,
            primary_ids,
            primary_bytes: total_bytes,
            secondary_ids: BTreeSet::new(),
            secondary_bytes: 0,
            entries,
        })
    }

    /// Parses the indexed non-village catalog: one base64+gzip NBT
    /// concatenation per family plus offset/length slices.
    pub fn from_indexed_json(text: &str) -> Result<Self, CatalogError> {
        let value: Value = serde_json::from_str(text)
            .map_err(|error| CatalogError::InvalidJson(error.to_string()))?;
        let root = value
            .as_object()
            .ok_or_else(|| invalid_catalog("root must be an object"))?;
        reject_unknown_keys(
            root,
            &[
                "blobs",
                "counts",
                "data_version",
                "nbt_bytes",
                "templates",
                "total_bytes",
                "version",
            ],
            "catalog",
        )?;

        let version = required_str(root, "version", "catalog")?.to_owned();
        if version != TARGET_VERSION {
            return Err(invalid_catalog(format!(
                "version {version} does not match target {TARGET_VERSION}"
            )));
        }
        let data_version = required_i32(root, "data_version", "catalog")?;
        if data_version != TARGET_DATA_VERSION {
            return Err(invalid_catalog(format!(
                "data version {data_version} does not match target {TARGET_DATA_VERSION}"
            )));
        }
        let total_bytes = required_usize(root, "total_bytes", "catalog")?;
        let nbt_bytes = required_usize(root, "nbt_bytes", "catalog")?;
        let template_count = parse_counts(root)?;

        let blobs = required_object(root, "blobs", "catalog")?;
        let mut shared = BTreeMap::<String, Arc<SharedBlob>>::new();
        let mut compressed_bytes = 0usize;
        let mut indexed_nbt_bytes = 0usize;
        for (name, value) in blobs {
            if name.is_empty() {
                return Err(invalid_catalog("blobs has an empty family key"));
            }
            let blob = value
                .as_object()
                .ok_or_else(|| invalid_catalog(format!("blob `{name}` must be an object")))?;
            reject_unknown_keys(blob, &["bytes", "payload"], "catalog blob")?;
            let bytes = required_usize(blob, "bytes", "catalog blob")?;
            if bytes == 0 {
                return Err(invalid_catalog(format!("blob `{name}` is empty")));
            }
            let payload = required_str(blob, "payload", "catalog blob")?;
            compressed_bytes = compressed_bytes.saturating_add(
                validate_base64(payload)
                    .map_err(|message| invalid_catalog(format!("blob `{name}`: {message}")))?,
            );
            indexed_nbt_bytes = indexed_nbt_bytes.saturating_add(bytes);
            if shared
                .insert(
                    name.clone(),
                    Arc::new(SharedBlob {
                        name: name.clone(),
                        payload: payload.to_owned(),
                        uncompressed_bytes: bytes,
                        decoded: OnceLock::new(),
                    }),
                )
                .is_some()
            {
                return Err(invalid_catalog(format!("duplicate blob `{name}`")));
            }
        }
        if compressed_bytes != total_bytes {
            return Err(invalid_catalog(format!(
                "catalog blobs decode to {compressed_bytes} bytes but total_bytes is {total_bytes}"
            )));
        }
        if indexed_nbt_bytes != nbt_bytes {
            return Err(invalid_catalog(format!(
                "catalog blobs hold {indexed_nbt_bytes} NBT bytes but nbt_bytes is {nbt_bytes}"
            )));
        }

        let templates = required_object(root, "templates", "catalog")?;
        let mut entries = BTreeMap::new();
        let mut slices = BTreeMap::<String, Vec<(usize, usize)>>::new();
        for (name, value) in templates {
            let id = normalize_structure_id(name);
            if id != *name {
                return Err(invalid_catalog(format!(
                    "template key `{name}` is not normalized (expected `{id}`)"
                )));
            }
            let index = value.as_object().ok_or_else(|| {
                invalid_catalog(format!("template `{id}` entry must be an object"))
            })?;
            reject_unknown_keys(index, &["blob", "length", "offset"], "catalog template")?;
            let blob_name = required_str(index, "blob", "catalog template")?;
            let length = required_usize(index, "length", "catalog template")?;
            let offset = required_usize(index, "offset", "catalog template")?;
            if length == 0 {
                return Err(invalid_catalog(format!(
                    "template `{id}` has an empty slice"
                )));
            }
            let blob = shared.get(blob_name).ok_or_else(|| {
                invalid_catalog(format!(
                    "template `{id}` references unknown blob `{blob_name}`"
                ))
            })?;
            let end = offset
                .checked_add(length)
                .ok_or_else(|| invalid_catalog(format!("template `{id}` slice overflows usize")))?;
            if end > blob.uncompressed_bytes {
                return Err(invalid_catalog(format!(
                    "template `{id}` slice {offset}..{end} exceeds blob `{blob_name}` ({} bytes)",
                    blob.uncompressed_bytes
                )));
            }
            slices
                .entry(blob_name.to_owned())
                .or_default()
                .push((offset, length));
            if entries
                .insert(
                    id.clone(),
                    CatalogEntry {
                        payload: CatalogPayload::Shared {
                            blob: Arc::clone(blob),
                            offset,
                            length,
                        },
                        parsed: OnceLock::new(),
                    },
                )
                .is_some()
            {
                return Err(invalid_catalog(format!("duplicate template id `{id}`")));
            }
        }

        if entries.len() != template_count {
            return Err(invalid_catalog(format!(
                "catalog has {} templates but counts.templates is {template_count}",
                entries.len()
            )));
        }
        for (blob_name, blob) in &shared {
            let mut ranges = slices.remove(blob_name).unwrap_or_default();
            if ranges.is_empty() {
                return Err(invalid_catalog(format!(
                    "blob `{blob_name}` is not referenced by any template"
                )));
            }
            ranges.sort_unstable();
            let mut expected = 0usize;
            for (offset, length) in ranges {
                if offset != expected {
                    return Err(invalid_catalog(format!(
                        "blob `{blob_name}` slices are not contiguous at offset {offset} (expected {expected})"
                    )));
                }
                expected = expected.checked_add(length).ok_or_else(|| {
                    invalid_catalog(format!("blob `{blob_name}` slice lengths overflow usize"))
                })?;
            }
            if expected != blob.uncompressed_bytes {
                return Err(invalid_catalog(format!(
                    "blob `{blob_name}` slices cover {expected} bytes but the blob is {} bytes",
                    blob.uncompressed_bytes
                )));
            }
        }

        Ok(Self {
            version,
            data_version,
            total_bytes,
            nbt_bytes,
            primary_ids: BTreeSet::new(),
            primary_bytes: 0,
            secondary_ids: entries.keys().cloned().collect(),
            secondary_bytes: total_bytes,
            entries,
        })
    }

    /// Merges a second (non-village) catalog into this one. Duplicate ids are
    /// an error. The merged templates become part of the primary+secondary
    /// [`all_len`](Self::all_len) view.
    pub fn merge(&mut self, other: Self) -> Result<(), CatalogError> {
        self.merge_impl(other, true)
    }

    /// Merges an additional catalog (trial chambers) into this one without
    /// moving the primary/secondary `all_*` pins. The templates are still
    /// available through lookup and the [`merged_len`](Self::merged_len) view.
    pub fn merge_additional(&mut self, other: Self) -> Result<(), CatalogError> {
        self.merge_impl(other, false)
    }

    fn merge_impl(&mut self, other: Self, track_secondary: bool) -> Result<(), CatalogError> {
        if self.version != other.version {
            return Err(invalid_catalog(format!(
                "cannot merge version {} with version {}",
                self.version, other.version
            )));
        }
        if self.data_version != other.data_version {
            return Err(invalid_catalog(format!(
                "cannot merge data version {} with data version {}",
                self.data_version, other.data_version
            )));
        }
        let other_ids: BTreeSet<String> = if track_secondary {
            if other.primary_ids.is_empty() && other.secondary_ids.is_empty() {
                other.entries.keys().cloned().collect()
            } else {
                other
                    .primary_ids
                    .iter()
                    .chain(other.secondary_ids.iter())
                    .cloned()
                    .collect()
            }
        } else {
            BTreeSet::new()
        };
        let other_secondary_bytes = if track_secondary {
            if other.primary_ids.is_empty() && other.secondary_ids.is_empty() {
                other.total_bytes
            } else {
                other.primary_bytes.saturating_add(other.secondary_bytes)
            }
        } else {
            0
        };
        for (id, entry) in other.entries {
            if self.entries.insert(id.clone(), entry).is_some() {
                return Err(invalid_catalog(format!(
                    "duplicate template id `{id}` across catalogs"
                )));
            }
        }
        self.total_bytes = self.total_bytes.saturating_add(other.total_bytes);
        self.nbt_bytes = self.nbt_bytes.saturating_add(other.nbt_bytes);
        self.secondary_ids.extend(other_ids);
        self.secondary_bytes = self.secondary_bytes.saturating_add(other_secondary_bytes);
        Ok(())
    }

    pub fn version(&self) -> &str {
        &self.version
    }

    pub fn data_version(&self) -> i32 {
        self.data_version
    }

    /// Number of templates in the primary (village) slice, or in this catalog
    /// when it was parsed without a separate primary slice.
    pub fn len(&self) -> usize {
        if self.primary_ids.is_empty() {
            self.entries.len()
        } else {
            self.primary_ids.len()
        }
    }

    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }

    /// Sum of the gzip-compressed payload bytes in the primary slice (or in
    /// this catalog when it has no separate primary slice).
    pub fn total_bytes(&self) -> usize {
        if self.primary_ids.is_empty() {
            self.total_bytes
        } else {
            self.primary_bytes
        }
    }

    /// Sum of the decompressed NBT bytes described by every loaded indexed
    /// catalog.
    pub fn nbt_bytes(&self) -> usize {
        self.nbt_bytes
    }

    /// Total templates across the primary and secondary catalogs (village plus
    /// non-village). This keeps the original 1,011-template pin when the
    /// trial-chamber catalog is loaded.
    pub fn all_len(&self) -> usize {
        self.primary_ids.len() + self.secondary_ids.len()
    }

    /// Total compressed payload bytes across the primary and secondary
    /// catalogs.
    pub fn all_total_bytes(&self) -> usize {
        self.primary_bytes.saturating_add(self.secondary_bytes)
    }

    /// Primary (village) template ids, or every id for a single catalog.
    pub fn ids(&self) -> impl Iterator<Item = &str> {
        self.entries
            .keys()
            .filter(|id| self.primary_ids.is_empty() || self.primary_ids.contains(*id))
            .map(String::as_str)
    }

    /// Primary and secondary template ids (village plus non-village), or every
    /// id when this catalog has no tier bookkeeping.
    pub fn all_ids(&self) -> impl Iterator<Item = &str> {
        self.entries
            .keys()
            .filter(|id| {
                self.primary_ids.is_empty() && self.secondary_ids.is_empty()
                    || self.primary_ids.contains(*id)
                    || self.secondary_ids.contains(*id)
            })
            .map(String::as_str)
    }

    /// Number of templates across every loaded catalog, including the
    /// trial-chamber parts.
    pub fn merged_len(&self) -> usize {
        self.entries.len()
    }

    /// Compressed payload bytes across every loaded catalog.
    pub fn merged_total_bytes(&self) -> usize {
        self.total_bytes
    }

    /// Decompressed NBT bytes across every loaded indexed catalog.
    pub fn merged_nbt_bytes(&self) -> usize {
        self.nbt_bytes
    }

    /// Every template id across every loaded catalog.
    pub fn merged_ids(&self) -> impl Iterator<Item = &str> {
        self.entries.keys().map(String::as_str)
    }

    pub fn contains(&self, name: &str) -> bool {
        self.entries.contains_key(&normalize_structure_id(name))
    }

    /// Whether this template has already been decompressed and parsed by the
    /// current thread.
    pub fn is_loaded(&self, name: &str) -> bool {
        let id = normalize_structure_id(name);
        LOADED_TEMPLATES.with(|loaded| loaded.borrow().contains(&id))
    }

    /// Materializes one template, caching the parsed result.
    ///
    /// Unknown ids and corrupt base64/gzip/NBT payloads return explicit
    /// [`CatalogError`] values rather than an empty template.
    pub fn template(&self, name: &str) -> Result<&StructureTemplate, CatalogError> {
        let id = normalize_structure_id(name);
        let entry = self
            .entries
            .get(&id)
            .ok_or_else(|| CatalogError::UnknownTemplate {
                template: id.clone(),
            })?;
        let parsed = entry.parsed.get_or_init(|| match &entry.payload {
            CatalogPayload::Inline(payload) => {
                let bytes =
                    decode_base64(payload).map_err(|message| format!("base64: {message}"))?;
                StructureTemplate::from_gzip(&bytes).map_err(|error| format!("gzip/NBT: {error}"))
            }
            CatalogPayload::Shared {
                blob,
                offset,
                length,
            } => {
                let decoded = blob.decoded.get_or_init(|| {
                    let bytes = decode_base64(&blob.payload).map_err(|message| {
                        format!("shared blob `{}` base64: {message}", blob.name)
                    })?;
                    decode_gzip(&bytes)
                        .map_err(|message| format!("shared blob `{}` gzip: {message}", blob.name))
                });
                let bytes = decoded.as_ref().map_err(|message| message.clone())?;
                let end = offset.saturating_add(*length);
                let slice = bytes.get(*offset..end).ok_or_else(|| {
                    format!(
                        "shared blob `{}` slice {offset}..{end} exceeds {} decoded bytes",
                        blob.name,
                        bytes.len()
                    )
                })?;
                let mut reader = slice;
                let root = nbt::read_root(&mut reader).map_err(|error| format!("NBT: {error}"))?;
                StructureTemplate::from_nbt(&root).map_err(|error| format!("NBT: {error}"))
            }
        });
        if parsed.is_ok() {
            LOADED_TEMPLATES.with(|loaded| {
                loaded.borrow_mut().insert(id.clone());
            });
        }
        parsed
            .as_ref()
            .map_err(|message| CatalogError::CorruptPayload {
                template: id,
                message: message.clone(),
            })
    }
}

impl TemplateProvider for StructureTemplateCatalog {
    fn template(&self, name: &str) -> Option<&StructureTemplate> {
        // `TemplateProvider` cannot carry an error. Callers that need to
        // distinguish "unknown" from "corrupt" use `StructureTemplateCatalog::template`.
        StructureTemplateCatalog::template(self, name).ok()
    }
}

/// Normalizes a structure-template id: strip a leading slash and `.nbt`, and
/// namespace bare ids as `minecraft:`.
pub fn normalize_structure_id(name: &str) -> String {
    let name = name.strip_prefix('/').unwrap_or(name);
    let name = name.strip_suffix(".nbt").unwrap_or(name);
    if name.contains(':') {
        name.to_owned()
    } else {
        format!("minecraft:{name}")
    }
}

fn parse_counts(root: &Map<String, Value>) -> Result<usize, CatalogError> {
    let counts = required_object(root, "counts", "catalog")?;
    reject_unknown_keys(counts, &["by_root", "templates"], "catalog counts")?;
    let template_count = required_usize(counts, "templates", "catalog counts")?;
    let by_root = required_object(counts, "by_root", "catalog counts")?;
    let mut by_root_total = 0usize;
    for (category, value) in by_root {
        if category.is_empty() {
            return Err(invalid_catalog("counts.by_root has an empty category"));
        }
        let count = value.as_u64().ok_or_else(|| {
            invalid_catalog(format!(
                "counts.by_root[{category}] must be an unsigned integer"
            ))
        })? as usize;
        by_root_total = by_root_total.saturating_add(count);
    }
    if by_root_total != template_count {
        return Err(invalid_catalog(format!(
            "counts.by_root sums to {by_root_total} but counts.templates is {template_count}"
        )));
    }
    Ok(template_count)
}

fn decode_gzip(input: &[u8]) -> Result<Vec<u8>, String> {
    let mut decoder = GzDecoder::new(input);
    let mut output = Vec::new();
    decoder
        .read_to_end(&mut output)
        .map_err(|error| error.to_string())?;
    Ok(output)
}

fn validate_base64(input: &str) -> Result<usize, String> {
    let bytes = input.as_bytes();
    if bytes.is_empty() {
        return Err("payload is empty".to_owned());
    }
    if !bytes.len().is_multiple_of(4) {
        return Err(format!(
            "base64 length {} is not a multiple of 4",
            bytes.len()
        ));
    }
    let padding = match bytes.last() {
        Some(b'=') if bytes.len() >= 2 && bytes[bytes.len() - 2] == b'=' => 2,
        Some(b'=') => 1,
        _ => 0,
    };
    for (index, byte) in bytes.iter().copied().enumerate() {
        let is_padding = byte == b'=' && index >= bytes.len() - padding;
        if !is_padding && base64_value(byte).is_none() {
            return Err(format!(
                "invalid base64 byte 0x{byte:02x} at offset {index}"
            ));
        }
    }
    Ok(bytes.len() / 4 * 3 - padding)
}

fn decode_base64(input: &str) -> Result<Vec<u8>, String> {
    validate_base64(input)?;
    let bytes = input.as_bytes();
    let mut output = Vec::with_capacity(bytes.len() / 4 * 3);
    let mut index = 0;
    while index < bytes.len() {
        let chunk = &bytes[index..index + 4];
        let a = base64_value(chunk[0]).ok_or_else(|| "invalid base64 byte".to_owned())?;
        let b = base64_value(chunk[1]).ok_or_else(|| "invalid base64 byte".to_owned())?;
        let c = if chunk[2] == b'=' {
            0
        } else {
            base64_value(chunk[2]).ok_or_else(|| "invalid base64 byte".to_owned())?
        };
        let d = if chunk[3] == b'=' {
            0
        } else {
            base64_value(chunk[3]).ok_or_else(|| "invalid base64 byte".to_owned())?
        };
        output.push((a << 2) | (b >> 4));
        if chunk[2] != b'=' {
            output.push((b << 4) | (c >> 2));
        }
        if chunk[3] != b'=' {
            output.push((c << 6) | d);
        }
        index += 4;
    }
    Ok(output)
}

fn base64_value(byte: u8) -> Option<u8> {
    match byte {
        b'A'..=b'Z' => Some(byte - b'A'),
        b'a'..=b'z' => Some(byte - b'a' + 26),
        b'0'..=b'9' => Some(byte - b'0' + 52),
        b'+' => Some(62),
        b'/' => Some(63),
        _ => None,
    }
}

fn required_str<'a>(
    object: &'a Map<String, Value>,
    key: &str,
    what: &str,
) -> Result<&'a str, CatalogError> {
    object
        .get(key)
        .and_then(Value::as_str)
        .ok_or_else(|| invalid_catalog(format!("{what} is missing a string `{key}`")))
}

fn required_object<'a>(
    object: &'a Map<String, Value>,
    key: &str,
    what: &str,
) -> Result<&'a Map<String, Value>, CatalogError> {
    object
        .get(key)
        .and_then(Value::as_object)
        .ok_or_else(|| invalid_catalog(format!("{what} is missing an object `{key}`")))
}

fn required_i32(object: &Map<String, Value>, key: &str, what: &str) -> Result<i32, CatalogError> {
    let value = object
        .get(key)
        .and_then(Value::as_i64)
        .ok_or_else(|| invalid_catalog(format!("{what} is missing an integer `{key}`")))?;
    i32::try_from(value)
        .map_err(|_| invalid_catalog(format!("{what} `{key}` is outside the i32 range")))
}

fn required_usize(
    object: &Map<String, Value>,
    key: &str,
    what: &str,
) -> Result<usize, CatalogError> {
    let value = object
        .get(key)
        .and_then(Value::as_u64)
        .ok_or_else(|| invalid_catalog(format!("{what} is missing an unsigned integer `{key}`")))?;
    usize::try_from(value)
        .map_err(|_| invalid_catalog(format!("{what} `{key}` is outside the usize range")))
}

fn reject_unknown_keys(
    object: &Map<String, Value>,
    allowed: &[&str],
    what: &str,
) -> Result<(), CatalogError> {
    for key in object.keys() {
        if !allowed.contains(&key.as_str()) {
            return Err(invalid_catalog(format!("{what} has unknown field `{key}`")));
        }
    }
    Ok(())
}

fn invalid_catalog(message: impl Into<String>) -> CatalogError {
    CatalogError::InvalidCatalog(message.into())
}
