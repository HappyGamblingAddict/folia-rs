//! Embedded vanilla structure-template catalogs.
//!
//! Three 1.21.11 structure NBT assets ship with the crate:
//!
//! 1. [`EMBEDDED_STRUCTURE_TEMPLATES`] contains the 483 `minecraft:village/**`
//!    templates. Each value is the base64 encoding of that template's original
//!    gzip-compressed NBT bytes.
//! 2. [`EMBEDDED_STRUCTURE_TEMPLATES_MORE`] contains the 528 remaining
//!    non-village templates (every family except `trial_chambers`). Each
//!    top-level family is one base64+gzip stream of concatenated NBT documents
//!    plus an offset/length index.
//! 3. [`EMBEDDED_STRUCTURE_TEMPLATES_TRIAL`] contains the 191
//!    `minecraft:trial_chambers/**` templates. To keep each compressed stream
//!    compact the family is split by its first subdirectory (`chamber`,
//!    `chests`, `corridor`, ...): each part is one base64+gzip stream plus
//!    the same offset/length index:
//!
//!    ```text
//!    "blobs":     { "<part>": { "bytes": N, "payload": "<base64 gzip>" } }
//!    "templates": { "<id>": { "blob": "<part>", "length": N, "offset": N } }
//!    ```
//!
//! Loading a template is:
//!
//! 1. base64-decode the entry (or its indexed part),
//! 2. gunzip it (part streams decompress once and are shared), and
//! 3. parse the NBT with [`StructureTemplate::from_gzip`] or
//!    [`StructureTemplate::from_nbt`], caching the result.
//!
//! All three assets are generated by `scripts/extract_structure_templates.ps1`
//! from the decompiled data tree and are byte-stable across runs.

