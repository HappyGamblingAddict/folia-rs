#requires -Version 5.1
<#
.SYNOPSIS
    Reproducibly regenerate and verify the Folia 1.21.11 oracle assets.

.DESCRIPTION
    Orchestrates the existing per-asset extractors in dependency order, stamps
    VERSION.txt, verifies the result with Cargo, and prints a SHA-256 manifest.
    This script contains no game logic and never copies Java dumps by hand: it
    only checks the inputs, invokes the existing extractors, and reports errors.

    With -Check it verifies VERSION.txt and the pinned asset hashes through
    `cargo test -p folia-core --test assets` without running any Java tool.
    Without -Check it first requires the external reference material from
    AGENTS.md (decompiled, java-tools, libraries, java-worldgen and the Folia
    jar), refuses to overwrite existing outputs unless -Force is supplied, then
    runs the extractors and the Cargo verification guard.

.PARAMETER Check
    Verify the target version and the current asset hashes/manifest without
    running the Java extractors. Runs the Cargo asset guard when Cargo is on
    PATH; fails loudly when it is not, rather than reporting a false pass.

.PARAMETER Force
    Allow the regeneration path to overwrite already-generated files. Without
    it (and without -Check) the script refuses to overwrite.

.PARAMETER ReferenceRoot
    Root of the external reference material. Defaults to ../rustfol next to
    this repository, then C:\Users\austr\Downloads\rustfol.
#>
[CmdletBinding()]
param(
    [switch]$Check,
    [switch]$Force,
    [string]$ReferenceRoot = ""
)

$ErrorActionPreference = "Stop"

$repoRoot = Split-Path -Parent $PSScriptRoot
Set-Location $repoRoot

$expectedVersion = "1.21.11"
$expectedDataVersion = "4788"
$versionPath = Join-Path $repoRoot "crates/folia-core/assets/VERSION.txt"

# The 27 assets pinned by crates/folia-core/tests/assets.rs, in the same order.
# Keep this list in sync with that test and with assets/ASSETS.md.
