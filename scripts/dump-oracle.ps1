        "block_state_behaviour.tsv.gz",
        "block_shapes.tsv.gz",
        "biome_climate.tsv",
        "block_defaults.tsv",
        "item_ids.tsv",
        "entity_type_ids.tsv",
        "biome_ids.txt",
        "mth_sin.bin",
        "feature_data.json",
        "tags/block.tsv",
        "tags/item.tsv",
        "tags/entity_type.tsv",
        "tags/fluid.tsv",
        "tags/game_event.tsv",
        "tags/damage_type.tsv",
        "tags/enchantment.tsv",
        "tags/point_of_interest_type.tsv",
        "tags/worldgen.tsv",
        "loot_tables.json",
        "recipes.json",
        "item_prototypes.json",
        "structure_processors.json",
        "template_pools.json",
        "structure_templates.json",
        "structure_templates_more.json",
        "structure_templates_trial.json"
    )
}

function Get-CargoCommand {
    $command = Get-Command cargo -ErrorAction SilentlyContinue
    if ($null -eq $command) { return $null }
    return $command.Source
}

function Read-VersionManifest {
    param([string]$Path)
    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) {
        throw "Version manifest not found: $Path"
    }
    $values = @{}
    foreach ($raw in [System.IO.File]::ReadAllLines($Path)) {
        $line = $raw.Trim()
        if ($line.Length -eq 0 -or $line.StartsWith("#")) { continue }
        $separator = $line.IndexOf("=")
        if ($separator -le 0) {
            throw ("Malformed line in {0}: {1}" -f $Path, $line)
        }
        $key = $line.Substring(0, $separator).Trim()
        $value = $line.Substring($separator + 1).Trim()
        $values[$key] = $value
    }
    return $values
}

function Assert-VersionManifest {
    param([string]$Path)
    $values = Read-VersionManifest -Path $Path
    $actualVersion = if ($values.ContainsKey("minecraft_version")) { $values["minecraft_version"] } else { "<missing>" }
    $actualDataVersion = if ($values.ContainsKey("data_version")) { $values["data_version"] } else { "<missing>" }
    if ($actualVersion -ne $expectedVersion) {
        throw "$Path declares minecraft_version '$actualVersion', expected '$expectedVersion'"
    }
    if ($actualDataVersion -ne $expectedDataVersion) {
        throw "$Path declares data_version '$actualDataVersion', expected '$expectedDataVersion'"
    }
    Write-Host "Version manifest OK: Minecraft $expectedVersion / DataVersion $expectedDataVersion"
}

function Write-VersionManifest {
    $lines = @(
        "# Target version for the generated assets in this directory.",
        "# Regenerated by scripts/dump-oracle.ps1; keep in sync with",
        "# crates/folia-core/src/asset_version.rs and the data_version",
        "# field stamped into the generated JSON catalogs.",
        "minecraft_version=$expectedVersion",
        "data_version=$expectedDataVersion",
        ""
    )
    $text = [string]::Join("`n", $lines)
    [System.IO.File]::WriteAllText($versionPath, $text, (New-Object System.Text.UTF8Encoding($false)))
    Write-Host "Refreshed $versionPath"
}

function Show-ManifestTable {
    Write-Host ""
    Write-Host ("{0,-40} {1,10}  {2}" -f "Asset", "Bytes", "SHA-256")
    Write-Host (("{0,-40} {1,10}  {2}" -f "", "", "") -replace " ", "-")
    foreach ($name in (Get-ManifestAssets)) {
        $path = Join-Path $repoRoot ("crates/folia-core/assets/" + $name)
        if (-not (Test-Path -LiteralPath $path -PathType Leaf)) {
            Write-Host ("{0,-40} {1,10}  {2}" -f $name, "MISSING", "-")
            continue
        }
        $length = (Get-Item -LiteralPath $path).Length
        $hash = (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash
        Write-Host ("{0,-40} {1,10}  {2}" -f $name, $length, $hash)
    }
}

function Resolve-ReferenceRootPath {
    if ($ReferenceRoot) {
        return [System.IO.Path]::GetFullPath($ReferenceRoot)
    }
    $parent = Split-Path -Parent $repoRoot
    $candidates = @(
        (Join-Path $parent "rustfol"),
        "C:\Users\austr\Downloads\rustfol"
    )
    foreach ($candidate in $candidates) {
        if (Test-Path -LiteralPath $candidate -PathType Container) {
            return [System.IO.Path]::GetFullPath($candidate)
        }
    }
    return [System.IO.Path]::GetFullPath("C:\Users\austr\Downloads\rustfol")
}

function Assert-ReferenceMaterial {
    param([string]$Root)
    $required = @(
        @{ Name = "decompiled Folia tree"; Path = (Join-Path $Root "decompiled") },
        @{ Name = "java-tools"; Path = (Join-Path $Root "java-tools") },
        @{ Name = "libraries"; Path = (Join-Path $Root "libraries") },
        @{ Name = "java-worldgen oracle"; Path = (Join-Path $Root "java-worldgen") },
        @{ Name = "Folia server jar"; Path = (Join-Path $Root "folia-1.21.11-14.jar") }
    )
    $missing = @()
    foreach ($item in $required) {
        if (-not (Test-Path -LiteralPath $item.Path)) {
            $missing += ("  - {0}: {1}" -f $item.Name, $item.Path)
        }
    }
    if ($missing.Count -gt 0) {
        $detail = $missing -join [Environment]::NewLine
        throw "External Java reference material is missing under '$Root'; no files were written.`n$detail`nPass -ReferenceRoot <dir> containing decompiled, java-tools, libraries, java-worldgen and folia-1.21.11-14.jar, or use -Check to validate the current version and hashes without the Java toolchain."
    }
    Write-Host "Reference material OK: $Root"
}

function Assert-OverwriteAllowed {
    if ($Force -or $Check) { return }
    $existing = @()
    foreach ($name in (Get-ManifestAssets)) {
        $path = Join-Path $repoRoot ("crates/folia-core/assets/" + $name)
        if (Test-Path -LiteralPath $path -PathType Leaf) { $existing += $name }
    }
    if ($existing.Count -gt 0) {
        throw "Refusing to overwrite $($existing.Count) existing generated assets without -Force. Re-run with -Force to regenerate, or -Check to verify the current files."
    }
}

function Invoke-Extractor {
    param(
        [string]$Name,
        [hashtable]$Parameters = @{}
    )
    $path = Join-Path $PSScriptRoot $Name
    if (-not (Test-Path -LiteralPath $path -PathType Leaf)) {
        throw "Extractor script not found: $path"
    }
    Write-Host "==> $Name"
    $global:LASTEXITCODE = 0
    try {
        & $path @Parameters
    }
    catch {
        throw "Extractor $Name failed: $($_.Exception.Message)"
    }
    if ($LASTEXITCODE -ne 0) {
        throw "Extractor $Name failed with exit code $LASTEXITCODE"
    }
}

function Invoke-CargoGuard {
    param([switch]$FormatCheck)
    $cargo = Get-CargoCommand
    if ($null -eq $cargo) {
        throw "cargo not found on PATH; asset hashes cannot be verified. Install Cargo or run 'cargo test -p folia-core --test assets' manually."
    }
    if ($FormatCheck) {
        Write-Host "Running cargo fmt --all -- --check..."
        & $cargo fmt --all -- --check
        if ($LASTEXITCODE -ne 0) {
            throw "cargo fmt --all -- --check failed with exit code $LASTEXITCODE"
        }
    }
    Write-Host "Running cargo test -p folia-core --test assets..."
    & $cargo test -p folia-core --test assets
    if ($LASTEXITCODE -ne 0) {
        throw "cargo test -p folia-core --test assets failed with exit code $LASTEXITCODE"
    }
}

function Invoke-Check {
    Assert-VersionManifest -Path $versionPath
    Invoke-CargoGuard
    Show-ManifestTable
    Write-Host "Check passed: version and pinned asset hashes are intact."
}

function Invoke-Regeneration {
    param([string]$Root)
    Assert-ReferenceMaterial -Root $Root
    Assert-OverwriteAllowed

    $jar = Join-Path $Root "folia-1.21.11-14.jar"
    $libraries = Join-Path $Root "libraries"
    $decompiled = Join-Path $Root "decompiled"

    Invoke-Extractor -Name "dump_registries.ps1"
    # extract_biome_climate.ps1 has no -ReferenceRoot parameter and reads the
    # documented decompiled tree itself; it is invoked with its defaults.
    Invoke-Extractor -Name "extract_biome_climate.ps1"
    Invoke-Extractor -Name "extract_block_shapes.ps1" -Parameters @{
        ServerJar = $jar; Libraries = $libraries; ReferenceRoot = $Root
    }
    Invoke-Extractor -Name "extract_item_prototypes.ps1" -Parameters @{
        ServerJar = $jar; LibraryRoot = $libraries
    }
    Invoke-Extractor -Name "extract_loot_recipes.ps1" -Parameters @{
        SourceRoot = $decompiled
    }
    Invoke-Extractor -Name "extract_tags.ps1" -Parameters @{
        ReferenceTags = (Join-Path $decompiled "data/minecraft/tags")
    }
    Invoke-Extractor -Name "extract_structure_data.ps1" -Parameters @{
        SourceRoot = $decompiled
    }
    Invoke-Extractor -Name "extract_structure_templates.ps1" -Parameters @{
        SourceRoot = (Join-Path $decompiled "data/minecraft/structure")
    }

    Write-VersionManifest
    Assert-VersionManifest -Path $versionPath
    Invoke-CargoGuard -FormatCheck
    Show-ManifestTable
    Write-Host "Regeneration complete: all extractors and verification guards passed."
}

if ($Check) {
    Invoke-Check
}
else {
    Invoke-Regeneration -Root (Resolve-ReferenceRootPath)
}
